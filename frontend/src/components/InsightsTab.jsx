"use client";
import { useState } from "react";
import { api } from "../api";
import { guarded } from "../guard";

// Filter tagged evidence, tick quotes, and turn them into an insight.
export default function InsightsTab({ data, reload, openNote, ai }) {
  const [filter, setFilter] = useState(new Set());
  const [picked, setPicked] = useState(new Set());
  const [title, setTitle] = useState("");
  const [description, setDescription] = useState("");
  const [suggested, setSuggested] = useState(null);

  const toggle = (set, setter, value) => {
    const next = new Set(set);
    if (next.has(value)) next.delete(value);
    else next.add(value);
    setter(next);
  };

  const allTags = [...new Set(data.highlights.flatMap((h) => h.tags))].sort();
  const shown = data.highlights.filter((h) => filter.size === 0 || h.tags.some((t) => filter.has(t)));
  const noteName = (id) => data.notes.find((n) => n.id === id).title;

  const create = async () => {
    try {
      await api("insights", "POST", { title, description, highlightIds: [...picked] });
      setPicked(new Set());
      setTitle("");
      setDescription("");
      reload();
    } catch (e) {
      window.alert(e.message);
    }
  };

  const suggest = async () => {
    try {
      setSuggested(await api("insights/suggest", "POST", {}));
    } catch (e) {
      window.alert(e.message);
    }
  };

  const accept = async (s) => {
    try {
      await api("insights", "POST", { title: s.title, description: s.description, highlightIds: s.highlightIds });
      setSuggested({ ...suggested, suggestions: suggested.suggestions.filter((x) => x !== s) });
      reload();
    } catch (e) {
      window.alert(e.message);
    }
  };

  const remove = guarded(async (id) => {
    await api("insights/" + id, "DELETE");
    reload();
  });

  return (
    <>
      <div className="card">
        <h2>Filter by tag</h2>
        {allTags.length === 0 && <div className="muted">Tag some highlights first.</div>}
        {allTags.map((t) => (
          <span key={t} className={"tag" + (filter.has(t) ? " on" : "")} onClick={() => toggle(filter, setFilter, t)}>{t}</span>
        ))}
      </div>

      <div className="card stack">
        <h2>Evidence ({shown.length}), tick quotes to build an insight</h2>
        {shown.length === 0 && <div className="muted">No highlights match.</div>}
        {shown.map((h) => (
          <label key={h.id} className="quote" style={{ display: "block", cursor: "pointer" }}>
            <input type="checkbox" checked={picked.has(h.id)} onChange={() => toggle(picked, setPicked, h.id)} />
            {h.text}
            <div className="muted">{noteName(h.noteId)} · {h.tags.join(", ")}</div>
          </label>
        ))}
        <input placeholder="Insight title (e.g. Onboarding confuses new users)" value={title} onChange={(e) => setTitle(e.target.value)} />
        <textarea rows={3} placeholder="What does the evidence tell you?" value={description} onChange={(e) => setDescription(e.target.value)} />
        <button className="primary" onClick={create}>Create insight from selected</button>
      </div>

      {ai && (
      <div className="card stack">
        <h2>AI-suggested insights</h2>
        <button onClick={suggest}>Suggest insights</button>
        {suggested && (
          <div className="muted" id="suggest-method">
            {suggested.method === "llm" ? `Generated by ${suggested.model}` : `Rule-based suggestions (${suggested.fallbackReason || "no recurring tags yet"})`}
          </div>
        )}
        {suggested && suggested.suggestions.length === 0 && <div className="muted">No suggestions yet. Tag more highlights.</div>}
        {suggested && suggested.suggestions.map((s) => (
          <div key={s.title} className="quote">
            <strong>{s.title}</strong> <span className="muted">{Math.round(s.confidence * 100)}% confidence, {s.highlightIds.length} quote(s)</span>
            <div>{s.description}</div>
            <button className="primary" onClick={() => accept(s)}>Accept</button>
          </div>
        ))}
      </div>
      )}

      <div className="card stack">
        <h2>Insights ({data.insights.length})</h2>
        {data.insights.length === 0 && <div className="muted">No insights yet.</div>}
        {data.insights.map((i) => (
          <div key={i.id}>
            <strong>{i.title}</strong>
            <p style={{ margin: "4px 0" }}>{i.description}</p>
            {i.highlightIds.map((id) => {
              const h = data.highlights.find((x) => x.id === id);
              return (
                <div key={id} className="quote clickable" onClick={() => openNote(h.noteId)}>
                  {h.text}
                  <div className="muted">↗ {noteName(h.noteId)}</div>
                </div>
              );
            })}
            <button className="danger" onClick={() => remove(i.id)}>Delete insight</button>
          </div>
        ))}
      </div>
    </>
  );
}
